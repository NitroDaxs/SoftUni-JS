//This function is responsible for finding the bigger number of two given numbers.
function findBiggerNumber(firstNumber, secondNumber) {
    if (firstNumber > secondNumber) {
        console.log(firstNumber);
    } else {
        console.log(secondNumber);
    }
}

findBiggerNumber(5, 3);
findBiggerNumber(6, 5);
findBiggerNumber(10, 10);
findBiggerNumber(-5, 5);